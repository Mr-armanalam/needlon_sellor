// Helpful friendly title formatter for snake_case keys
export function formatFieldLabel(key: string): string {
  return key
    .split("_")
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(" ")
    .replace("Over Suit", "(Over Suit)")
    .replace("With Heels", "(With Heels)")
    .replace("Waist To Floor", "(Waist to Floor)");
}

